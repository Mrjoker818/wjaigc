export function createWorkflowFromPreset(preset: WorkflowPreset): Workflow {
  const workflow = createEmptyWorkflow(preset.name);
  workflow.description = preset.description;
  const nodes = preset.nodes.map((definition, index) => {
    const node = createWorkflowNode(definition.type, 80 + index * 280, 200, definition.label);
    if (definition.config) node.config = { ...node.config, ...definition.config };
    return node;
  });
  workflow.nodes = nodes;
  for (const connection of preset.connections) {
    const from = nodes[connection.from];
    const to = nodes[connection.to];
    if (!from || !to) throw new Error(`Invalid node index in workflow preset ${preset.id}`);
    const edge = createConnection(from.id, connection.fromPort, to.id, connection.toPort, connection.type);
    if (!isWorkflowConnectionValid(workflow, edge)) {
      throw new Error(`Invalid connection in workflow preset ${preset.id}: ${connection.fromPort} → ${connection.toPort}`);
    }
    workflow.connections.push(edge);
  }
  return autoLayoutWorkflow(workflow);
}
